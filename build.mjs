// Builds the published index.html: one self-contained page with all the JavaScript
// (src/ + data/, bundled and minified by esbuild) and the CSS inlined, plus a Content
// Security Policy that only allows those exact inline scripts (by sha256 hash).
// Edit the code under src/ and data/, play it with dev.html, then run `npm run build`.
// The result works at any path (michaelsturrup.com/plague-it/) and straight from disk.
//
// The build fails if dev.html references a local file that didn't get inlined, because
// the published page is only index.html: anything else would be missing in production.

import { build as esbuild } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('.', import.meta.url));
const CSS_TAG = '<link rel="stylesheet" href="src/styles.css">';
const JS_TAG = '<script type="module" src="src/main.js"></script>';

// Options (for tests): quiet, source (dev.html text to build from), write (default true).
export async function build({ quiet = false, source = null, write = true } = {}) {
  const js = await esbuild({
    absWorkingDir: ROOT,
    entryPoints: ['src/main.js'],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    minify: true,
    write: false,
    legalComments: 'none',
  });
  const css = await esbuild({
    absWorkingDir: ROOT,
    entryPoints: ['src/styles.css'],
    bundle: true,
    minify: true,
    write: false,
  });
  const dev = source ?? readFileSync(ROOT + 'dev.html', 'utf8');
  for (const tag of [CSS_TAG, JS_TAG]) {
    if (!dev.includes(tag)) throw new Error(`build: dev.html no longer contains ${tag}; update build.mjs to match.`);
  }
  let html = dev
    .replace(CSS_TAG, () => `<style>${css.outputFiles[0].text.trim()}</style>`)
    .replace(JS_TAG, () => `<script type="module">${js.outputFiles[0].text.trim().replaceAll('</script', '<\\/script')}</script>`)
    .replace(/^<!doctype html>\n/i, (m) => `${m}<!-- Generated by build.mjs from dev.html, src/ and data/. Do not edit: run \`npm run build\`. -->\n`);

  // Anything still pointing at a local file would 404 once published.
  const leftovers = [...html.matchAll(/\s(?:src|href)\s*=\s*["']([^"']*)["']/gi)]
    .map((m) => m[1])
    .filter((url) => !/^(#|data:|blob:|https?:|mailto:)/i.test(url));
  if (leftovers.length) {
    throw new Error(`build: dev.html references files that weren't inlined: ${leftovers.join(', ')}`);
  }

  html = withCsp(html);
  if (write) writeFileSync(ROOT + 'index.html', html);
  if (!quiet) console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB`);
  return html;
}

// Only this page's own inline scripts may run (allowed by hash, so an injected <script>
// won't), and the page may load nothing from any other site.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  if (!page.includes('<meta charset="utf-8">')) throw new Error('build: dev.html needs <meta charset="utf-8">');
  return page.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    await build();
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
