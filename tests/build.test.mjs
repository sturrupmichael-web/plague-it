// The build: one self-contained index.html with a strict CSP and nothing external.

import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { assert, ROOT } from './harness.mjs';
import { GAME_URL } from '../src/share.js';
import { build } from '../build.mjs';

export const tests = [
  ['index.html is self-contained with a hash-based CSP', async () => {
    const html = await build({ quiet: true });
    assert(html.startsWith('<!doctype html>\n<!-- Generated by build.mjs'), 'missing generated comment');
    assert(!/\s(src|href)=["'](?!#|data:|https?:)/i.test(html), 'still references a local file');
    assert(!html.includes('src/main.js') && !html.includes('src/styles.css'), 'source paths left in the page');
    const csp = html.match(/<meta http-equiv="Content-Security-Policy" content="([^"]+)">/)?.[1];
    assert(csp, 'no CSP meta tag');
    for (const part of ["default-src 'self'", "style-src 'self' 'unsafe-inline'", "img-src 'self' data: blob:", "connect-src 'self'", "object-src 'none'", "base-uri 'none'", "form-action 'none'"]) {
      assert(csp.includes(part), 'CSP missing ' + part);
    }
    const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
    assert(scripts.length >= 2, 'expected the boot script and the game bundle');
    for (const s of scripts) {
      const h = `'sha256-${createHash('sha256').update(s).digest('base64')}'`;
      assert(csp.includes(h), 'an inline script is not allowed by the CSP');
    }
    // (The one link allowed is the game's own address, which Share score sends people to.)
    const text = html.replace(/<!--[\s\S]*?-->/g, '').replaceAll(GAME_URL, '');
    assert(!/https?:\/\/(?!www\.w3\.org)/.test(text), 'the page mentions another site');
  }],

  ['the build fails if dev.html references a file that is not inlined', async () => {
    const source = readFileSync(ROOT + 'dev.html', 'utf8').replace('</head>', '  <link rel="icon" href="icon.png">\n</head>');
    let message = '';
    try {
      await build({ quiet: true, source, write: false });
    } catch (e) {
      message = e.message;
    }
    assert(message.includes('icon.png'), 'build did not fail: ' + message);
  }],
];
